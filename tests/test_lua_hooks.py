#!/usr/bin/env python3
"""
Test LuaJIT 2.1 Extensibility Hooks for Apex
Tests:
- access_by_lua_block blocking unauthorized requests (403)
- access_by_lua_block allowing authorized requests
- content_by_lua_block generating dynamic HTTP response via apex.say
- header_filter_by_lua_block modifying response headers via apex.resp.set_header
- apex.req.get_method, get_uri, get_header
"""

import http.client
import os
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import unittest

def find_free_port():
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(('', 0))
        return s.getsockname()[1]

class TestLuaHooks(unittest.TestCase):
    def setUp(self):
        self.tmp_dir = tempfile.mkdtemp(prefix='apex_lua_test_')
        self.port = find_free_port()
        self.conf_path = os.path.join(self.tmp_dir, 'apex.conf')
        self.apex_bin = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith('-') else './apex'

    def tearDown(self):
        if hasattr(self, 'proc') and self.proc:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=3)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        shutil.rmtree(self.tmp_dir, ignore_errors=True)

    def start_apex(self, conf_content):
        with open(self.conf_path, 'w') as f:
            f.write(conf_content)
        self.proc = subprocess.Popen(
            [self.apex_bin, '-c', self.conf_path],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True
        )
        time.sleep(0.3)
        poll_res = self.proc.poll()
        if poll_res is not None:
            self.fail(f"Apex died on start with exit code {poll_res}: {self.proc.stderr.read()}")

    def test_lua_access_control_and_content(self):
        conf = f"""
http {{
    server {{
        listen {self.port};
        server_name localhost;

        location /protected {{
            access_by_lua_block {{
                local token = apex.req.get_header("X-Token")
                if token ~= "secret123" then
                    apex.exit(403)
                end
            }}
            content_by_lua_block {{
                local method = apex.req.get_method()
                local uri = apex.req.get_uri()
                apex.say("Authorized: " .. method .. " " .. uri .. "\\n")
            }}
        }}

        location /header_test {{
            header_filter_by_lua_block {{
                apex.resp.set_header("X-Custom-Engine", "LuaJIT-2.1")
            }}
            content_by_lua_block {{
                apex.say("Header modified\\n")
            }}
        }}
    }}
}}
"""
        self.start_apex(conf)

        conn = http.client.HTTPConnection('127.0.0.1', self.port, timeout=5)

        # 1. Access /protected without token -> 403 Forbidden
        conn.request('GET', '/protected')
        resp = conn.getresponse()
        body = resp.read().decode('utf-8')
        self.assertEqual(resp.status, 403)
        self.assertIn("403", body)

        # 2. Access /protected with wrong token -> 403 Forbidden
        conn.request('GET', '/protected', headers={'X-Token': 'wrong'})
        resp = conn.getresponse()
        body = resp.read().decode('utf-8')
        self.assertEqual(resp.status, 403)

        # 3. Access /protected with valid token -> 200 OK + content generated by Lua
        conn.request('GET', '/protected', headers={'X-Token': 'secret123'})
        resp = conn.getresponse()
        body = resp.read().decode('utf-8')
        self.assertEqual(resp.status, 200)
        self.assertEqual(body, "Authorized: GET /protected\n")

        # 4. Access /header_test -> custom header injected by Lua
        conn.request('GET', '/header_test')
        resp = conn.getresponse()
        body = resp.read().decode('utf-8')
        self.assertEqual(resp.status, 200)
        self.assertEqual(resp.getheader('X-Custom-Engine'), 'LuaJIT-2.1')
        self.assertEqual(body, "Header modified\n")

        conn.close()

if __name__ == '__main__':
    args = [sys.argv[0]]
    if len(sys.argv) > 1 and not sys.argv[1].startswith('-'):
        args.extend(sys.argv[2:])
    else:
        args.extend(sys.argv[1:])
    unittest.main(argv=args)
